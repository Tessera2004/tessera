  const SUPPORTED = ['de', 'fr', 'it', 'es', 'en'];
  const LS_KEY = 'mosaos-lang';
  const LS_REGION = 'mosaos-region';

  /* Region (Ländercode) aus Browser-Locale extrahieren — z.B. de-CH → CH, es-ES → ES */
  function detectRegion() {
    const saved = localStorage.getItem(LS_REGION);
    if (saved) return saved;
    const langs = navigator.languages || [navigator.language || ''];
    for (const l of langs) {
      const parts = l.split('-');
      if (parts.length > 1) return parts[1].toUpperCase();
    }
    // Fallback über Zeitzone
    try {
      const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
      if (tz.startsWith('Europe/Zurich')) return 'CH';
      if (tz.startsWith('Europe/Berlin')) return 'DE';
      if (tz.startsWith('Europe/Vienna')) return 'AT';
      if (tz.startsWith('Europe/Paris')) return 'FR';
      if (tz.startsWith('Europe/Rome')) return 'IT';
      if (tz.startsWith('Europe/Madrid')) return 'ES';
    } catch {}
    return 'CH';
  }

  function detect() {
    /* Sprachseiten (/fr/, /it/ …) sind bereits übersetzt ausgeliefert.
       Sie setzen MOSAOS_LANG_FIXED — sonst würde diese Erkennung den
       fertigen Text sofort wieder auf die Browsersprache umschreiben. */
    if (window.MOSAOS_LANG_FIXED && SUPPORTED.includes(window.MOSAOS_LANG_FIXED)) {
      return window.MOSAOS_LANG_FIXED;
    }
    // 1. Manuelle Wahl
    const saved = localStorage.getItem(LS_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    // 2. Browser-Sprache
    const langs = navigator.languages || [navigator.language || 'de'];
    for (const l of langs) {
      const short = l.toLowerCase().slice(0, 2);
      if (SUPPORTED.includes(short)) return short;
    }
    // 3. Fallback via Region
    const region = detectRegion();
    const regionMap = { CH: 'de', DE: 'de', AT: 'de', FR: 'de', IT: 'de', ES: 'es' };
    return regionMap[region] || 'en';
  }

  function apply(lang) {
    const dict = DICT[lang] || DICT.de;
    const fallback = DICT.de;
    document.documentElement.lang = lang;
    let touchedHtml = false;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      const val = dict[key] != null ? dict[key] : fallback[key];
      if (val == null) return;
      if (val.includes('&') || val.includes('<')) { el.innerHTML = val; touchedHtml = true; }
      else el.textContent = val;
    });
    // Platzhalter (inputs/textarea) übersetzen
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder;
      const val = dict[key] != null ? dict[key] : fallback[key];
      if (val != null) el.setAttribute('placeholder', val);
    });
    // data-cfg-Spans, die in einem gerade per innerHTML ersetzten Block lagen,
    // erneut befüllen (config.js läuft sonst nur einmal beim Laden).
    if (touchedHtml && window.MOSAOS_CONFIG_FILL) window.MOSAOS_CONFIG_FILL(document);
    document.querySelectorAll('.lang-switch button').forEach((b) => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
    // Mixer neu rendern, falls geladen
    if (window.MOSAOS_MIXER_REFRESH) window.MOSAOS_MIXER_REFRESH();
    // Andere Skripte (z. B. das Cookie-Banner in config.js) informieren
    try {
      document.dispatchEvent(new CustomEvent('mosa-lang-changed', { detail: { lang } }));
    } catch (e) { /* alte Browser — dann bleibt nur die data-i18n-Übersetzung */ }
  }

  /* Einzelnen Text holen (für dynamisch erzeugte Elemente) */
  function t(key, lang) {
    const l = lang || document.documentElement.lang || detect();
    const dict = DICT[l] || DICT.de;
    return dict[key] != null ? dict[key] : (DICT.de[key] != null ? DICT.de[key] : key);
  }

  function set(lang) {
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(LS_KEY, lang);
    apply(lang);
  }

  window.MOSAOS_I18N = { detect, detectRegion, apply, set, t, supported: SUPPORTED, dict: DICT };

  document.addEventListener('DOMContentLoaded', () => {
    apply(detect());
    document.querySelectorAll('.lang-switch button[data-lang]').forEach((btn) => {
      btn.addEventListener('click', () => set(btn.dataset.lang));
    });
  });
