const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {stripTypeScriptTypes}=require('node:module');
const file=fs.readFileSync(require.resolve('../supabase/functions/_shared/booking-slots.ts'),'utf8');
const js=stripTypeScriptTypes(file,{mode:'strip'}).replaceAll('export function','function');
const context={};vm.createContext(context);vm.runInContext(js,context);
const {serviceDuration,overlaps,slotMinutes,calendarEvent}=context;
assert.equal(serviceDuration({A:{duration:60,buffer:15}},'A').duration,60);
assert.equal(serviceDuration({A:{duration:60,buffer:15}},'A').buffer,15);
assert.equal(serviceDuration(undefined,'A').duration,30);
assert.equal(serviceDuration({A:{duration:'bad'}},'A').duration,30);
assert.equal(overlaps(540,75,600,30),true);
assert.equal(overlaps(540,75,615,30),false);
assert.equal(overlaps(600,30,540,75),true);
assert.equal(overlaps(slotMinutes('2026-09-27','23:30'),90,slotMinutes('2026-09-28','00:15'),30),true);
const ics=calendarEvent('test','2026-10-25','10:00',60,'Europe/Zurich','Beratung, Test\nTermin');
assert.ok(ics.includes('DTSTART;TZID=Europe/Zurich:20261025T100000'));
assert.ok(ics.includes('DTEND;TZID=Europe/Zurich:20261025T110000'));
assert.ok(ics.includes('SUMMARY:Beratung\\, Test\\nTermin'));
console.log('PASS: duration, buffer, adjacency, overlap across midnight, calendar wall-clock timezone and escaping.');
